let op = '-';
let numA = 5, numB = 3;
switch(op) {
  case '+': console.log("Addition of Numbers :", numA + numB); break;
  case '-': console.log("Subtaction of Numbers :", numA - numB); break;
  case '*': console.log("Multiplication of Numbers :",numA * numB); break;
  case '/': console.log("Division of Numbers :", numA / numB); break;
  default: console.log("Invalid operation");
}
